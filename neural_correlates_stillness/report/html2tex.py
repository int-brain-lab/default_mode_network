"""Typeset a report page (<name>.html) as <name>.tex / <name>.pdf next to it, so the PDF carries the page's text.

Figures fig<N>_<name>.png are replaced by fig<N>_<name>_panels.pdf with the caption from fig<N>_<name>.tex
(written by save_with_caption); other figures (fig7_robustness) use their PDF and the page's figcaption.
Figure numbers follow the file names (fig12_* -> Figure 12, figS1_* -> Figure S1).
Usage: python html2tex.py                                  # stillness.html
       python html2tex.py ../../comprehensive_report/dmn_grey.html  # the grey-screen DMN report
"""
import re
import subprocess
import sys
from html.parser import HTMLParser
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIR = HERE  # folder of the page and its figures, set in main()
VOID = {"meta", "link", "img", "br", "hr"}

PREAMBLE = r"""% Generated by html2tex.py from stillness.html; edit the page, not this file.
\documentclass[10pt,a4paper]{article}
\usepackage[T1]{fontenc}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage[margin=2cm]{geometry}
\usepackage{graphicx}
\usepackage{amsmath}
\usepackage{booktabs}
\usepackage{tabularx}
\usepackage{xltabular}
\usepackage[table]{xcolor}
\usepackage{enumitem}
\usepackage{caption}
\usepackage[hidelinks]{hyperref}
\usepackage{titlesec}
\usepackage[breakable]{tcolorbox}
\definecolor{accent}{HTML}{ACCENT}
\definecolor{okc}{HTML}{0f7a52}
\definecolor{partc}{HTML}{b06a00}
\definecolor{noc}{HTML}{b5403a}
\definecolor{muted}{HTML}{6b6a66}
\captionsetup{font={sf,footnotesize},labelfont={sf,bf,footnotesize},justification=justified,singlelinecheck=false}
\setlist{itemsep=2pt,topsep=3pt,leftmargin=1.4em}
\titleformat{\section}{\large\bfseries}{}{0em}{}
\titleformat{\subsection}{\normalsize\bfseries}{}{0em}{}
\setlength{\parindent}{0pt}
\setlength{\parskip}{5pt}
\setlength{\emergencystretch}{3em}
\renewcommand{\topfraction}{0.9}
\renewcommand{\bottomfraction}{0.8}
\renewcommand{\textfraction}{0.07}
\renewcommand{\floatpagefraction}{0.85}
\begin{document}
"""

CHARS = {"\u2212": "$-$", "\u2265": "$\\geq$", "\u2264": "$\\leq$", "\u03c1": "$\\rho$", "\u00d7": "$\\times$",
         "\u00b1": "$\\pm$", "\u2082": "$_2$", "\u2020": "$\\dagger$", "\u2013": "--", "\u2014": "---",
         "\u201c": "``", "\u201d": "''", "\u2019": "'", "\u2018": "`", "\u2026": "\\ldots{}", "\u00a0": "~",
         "\u00b7": "$\\cdot$", "\u2192": "$\\rightarrow$", "\u25cf": "$\\bullet$", "~": "\\textasciitilde{}",
         "&": "\\&", "%": "\\%", "$": "\\$", "#": "\\#", "_": "\\_", "{": "\\{", "}": "\\}", "^": "\\^{}",
         "\\": "\\textbackslash{}", "<": "$<$", ">": "$>$"}


def esc(t):
    return "".join(CHARS.get(c, c) for c in t)


class Node:
    def __init__(self, tag, attrs, parent=None):
        self.tag, self.attrs, self.parent, self.kids = tag, dict(attrs), parent, []


class Tree(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = self.cur = Node("root", [])

    def handle_starttag(self, tag, attrs):
        n = Node(tag, attrs, self.cur)
        self.cur.kids.append(n)
        if tag not in VOID:
            self.cur = n

    def handle_endtag(self, tag):
        n = self.cur
        while n is not self.root and n.tag != tag:
            n = n.parent
        if n is not self.root:
            self.cur = n.parent

    def handle_data(self, data):
        self.cur.kids.append(data)


def cls(n):
    return n.attrs.get("class", "") or ""


def inline(n):
    if isinstance(n, str):
        return esc(re.sub(r"\s+", " ", n))
    body = "".join(inline(k) for k in n.kids)
    t = n.tag
    if t == "strong" or t == "b":
        return f"\\textbf{{{body}}}"
    if t == "em" or t == "i":
        return f"\\emph{{{body}}}"
    if t == "sub":
        return f"\\textsubscript{{{body}}}"
    if t == "sup":
        return f"\\textsuperscript{{{body}}}"
    if t == "code":
        return "\\texttt{" + body.replace("\\_", "\\_\\allowbreak{}").replace("/", "/\\allowbreak{}") + "}"
    if t == "a":
        href = n.attrs.get("href", "").replace("%", r"\%").replace("#", r"\#")
        return f"\\href{{{href}}}{{{body}}}" if href.startswith("http") else body
    if t == "span" and "verdict" in cls(n):
        col = "okc" if "v-ok" in cls(n) else "noc" if "v-no" in cls(n) else "partc"
        return f"\\textcolor{{{col}}}{{\\textbf{{{body}}}}}"
    if t == "br":
        return "\\\\"
    return body


def caption_from_tex(stem):
    s = (DIR / f"{stem}.tex").read_text()
    i = s.index("\\caption{") + len("\\caption{")
    depth, j = 1, i
    while depth:
        depth += {"{": 1, "}": -1}.get(s[j], 0)
        j += 1
    return s[i:j - 1]


def figure(n):
    img = next(k for k in n.kids if not isinstance(k, str) and k.tag == "img")
    stem = Path(img.attrs["src"]).stem
    if (DIR / f"{stem}_panels.pdf").exists() and (DIR / f"{stem}.tex").exists():
        pdf, cap = f"{stem}_panels.pdf", caption_from_tex(stem)
    else:
        fc = [k for k in n.kids if not isinstance(k, str) and k.tag == "figcaption"]
        pdf = f"{stem}.pdf"
        cap = re.sub(r"^Figure \d+\.\s*", "", inline(fc[0]).strip()) if fc else ""
    m = re.match(r"fig(S?)(\d+)_", stem)
    num = (f"\\renewcommand{{\\thefigure}}{{{m.group(1)}\\arabic{{figure}}}}\\setcounter{{figure}}{{{int(m.group(2)) - 1}}}\n"
           if m else "")
    width = "0.5\\linewidth" if "narrow" in cls(n) else "\\linewidth"
    return (f"\\begin{{figure}}[!htbp]\n{num}\\centering\n\\includegraphics[width={width}]{{{pdf}}}\n"
            f"\\caption{{{cap}}}\n\\label{{fig:{stem}}}\n\\end{{figure}}\n")


def table(n):
    rows = []
    for tr in iter_tag(n, "tr"):
        cells = [c for c in tr.kids if not isinstance(c, str) and c.tag in ("td", "th")]
        rows.append(([inline(c).strip() for c in cells], cells[0].tag == "th"))
    ncol = max(len(r) for r, _ in rows)
    # column widths grow with the square root of their longest entry; numbers right-aligned
    longest = [max(len(re.sub(r"\\[a-z]+|[{}$]", "", r[i])) if i < len(r) else 0 for r, _ in rows) for i in range(ncol)]
    w = [max(L, 6) ** 0.5 for L in longest]
    w = [x * ncol / sum(w) for x in w]
    numeric = [all(re.fullmatch(r"[-+0-9.,%~()\[\] $\\a-z]*", r[i]) and re.search(r"[0-9]", r[i])
                   for r, h in rows if not h and i < len(r) and r[i]) for i in range(ncol)]
    spec = "".join(f">{{\\hsize={x:.3f}\\hsize\\{'raggedleft' if numeric[i] and i else 'raggedright'}\\arraybackslash}}X"
                   for i, x in enumerate(w))
    out = ["{\\small\\renewcommand{\\arraystretch}{1.2}", f"\\begin{{xltabular}}{{\\linewidth}}{{{spec}}}", "\\toprule"]
    for r, head in rows:
        out.append(" & ".join(f"\\textbf{{{c}}}" if head else c for c in r) + " \\\\")
        if head:
            out += ["\\midrule", "\\endhead"]
    out += ["\\bottomrule", "\\end{xltabular}}"]
    return "\n".join(out) + "\n\n"


def iter_tag(n, tag):
    for k in n.kids:
        if isinstance(k, str):
            continue
        if k.tag == tag:
            yield k
        else:
            yield from iter_tag(k, tag)


def block(n):
    if isinstance(n, str):
        return "" if not n.strip() else esc(n.strip()) + "\n\n"
    t, c = n.tag, cls(n)
    if t in ("nav", "style", "script", "title", "meta", "link"):
        return ""
    if t == "div" and "eyebrow" in c:
        return f"{{\\small\\color{{muted}} {inline(n).strip()}}}\\\\[4pt]\n"
    if t == "h1":
        return f"{{\\LARGE\\bfseries {inline(n).strip()}}}\\\\[4pt]\n"
    if t == "p" and "authors" in c:
        return f"{{\\normalsize {inline(n).strip()}}}\\\\[2pt]\n{{\\color{{accent}}\\rule{{\\linewidth}}{{1.2pt}}}}\n\n"
    if t == "div" and "part" in c.split():
        lab = next(k for k in n.kids if not isinstance(k, str) and "partlabel" in cls(k))
        num = next(k for k in lab.kids if not isinstance(k, str) and "partnum" in cls(k))
        title = "".join(inline(k) for k in lab.kids if k is not num).strip()
        rest = "".join(block(k) for k in n.kids if k is not lab)
        brk = "" if "noclear" in c.split() else "\\clearpage\n"
        return (f"{brk}{{\\small\\bfseries\\color{{accent}} {inline(num).strip().upper()}}}\\\\[2pt]\n"
                f"{{\\LARGE\\bfseries {title}}}\\par\\medskip\n\n" + rest)
    if t == "h2" and "major" in c.split():
        brk = "\\clearpage\n" if "newpage" in c.split() else "\\bigskip\n"
        return f"{brk}{{\\LARGE\\bfseries {inline(n).strip()}}}\\par\\smallskip{{\\color{{accent}}\\rule{{\\linewidth}}{{0.8pt}}}}\\par\\medskip\n"
    if t == "h2":
        return f"\\section{{{inline(n).strip()}}}\n"
    if t == "h3":
        return f"\\subsection{{{inline(n).strip()}}}\n"
    if t == "p":
        txt = inline(n).strip()
        return f"{{\\small\\color{{muted}} {txt}}}\n\n" if "note" in c else txt + "\n\n"
    if t == "ul":
        items = "".join(f"\\item {li_body(li)}\n" for li in n.kids if not isinstance(li, str) and li.tag == "li")
        return f"\\begin{{itemize}}\n{items}\\end{{itemize}}\n"
    if t == "figure":
        return figure(n)
    if t == "table":
        return table(n)
    if t == "aside":
        inner = "".join(block(k) for k in n.kids)
        return ("\\begin{tcolorbox}[breakable,colback=accent!8,colframe=accent,boxrule=0pt,leftrule=2pt,"
                "arc=0pt,fontupper=\\small]\n" + inner + "\\end{tcolorbox}\n\n")
    return "".join(block(k) for k in n.kids)


def li_body(li):
    """Item text and nested lists in document order (text after a nested list stays after it)."""
    out = []
    for k in li.kids:
        out.append("\n" + block(k) if not isinstance(k, str) and k.tag == "ul" else inline(k))
    return "".join(out).strip()


def main():
    global DIR
    page = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE / "stillness.html"
    DIR = page.parent
    html = page.read_text()
    accent = re.search(r"--accent:\s*#([0-9a-fA-F]{6})", html).group(1)
    tree = Tree()
    tree.feed(html)
    wrap = next(n for n in iter_tag(tree.root, "div") if "wrap" in cls(n))
    tex = PREAMBLE.replace("stillness.html", page.name).replace("ACCENT", accent) + block(wrap) + "\\end{document}\n"
    (DIR / f"{page.stem}.tex").write_text(tex)
    subprocess.run(["tectonic", f"{page.stem}.tex"], cwd=DIR, check=True)


if __name__ == "__main__":
    main()
